#!/usr/bin/env node
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { spawn } from "node:child_process";

function todayUtc() {
  return new Date().toISOString().slice(0, 10);
}

function firstDayOfUtcMonth() {
  const now = new Date();
  return `${now.getUTCFullYear()}-${String(now.getUTCMonth() + 1).padStart(2, "0")}-01`;
}

function parseArgs(argv) {
  const options = {
    cliPath: "dist/cli.js",
    startDate: firstDayOfUtcMonth(),
    endDate: todayUtc(),
    readBurst: 1,
    commandTimeoutSeconds: 90,
    mutationRetries: 2,
    retryDelaySeconds: 2,
    includePaymentLinks: false,
    paymentAmount: 5,
    verbose: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = () => {
      const value = argv[index + 1];
      if (!value || value.startsWith("--")) {
        throw new Error(`${arg} requires a value`);
      }
      index += 1;
      return value;
    };

    if (arg === "--base-url") {
      options.baseUrl = next();
    } else if (arg === "--wallets") {
      options.walletsPath = next();
    } else if (arg === "--cli-path") {
      options.cliPath = next();
    } else if (arg === "--start-date") {
      options.startDate = next();
    } else if (arg === "--end-date") {
      options.endDate = next();
    } else if (arg === "--read-burst") {
      const value = Number(next());
      if (!Number.isInteger(value) || value < 0) {
        throw new Error("--read-burst must be a non-negative integer");
      }
      options.readBurst = value;
    } else if (arg === "--command-timeout") {
      const value = Number(next());
      if (!Number.isFinite(value) || value <= 0) {
        throw new Error("--command-timeout must be a positive number of seconds");
      }
      options.commandTimeoutSeconds = value;
    } else if (arg === "--mutation-retries") {
      const value = Number(next());
      if (!Number.isInteger(value) || value < 0) {
        throw new Error("--mutation-retries must be a non-negative integer");
      }
      options.mutationRetries = value;
    } else if (arg === "--retry-delay") {
      const value = Number(next());
      if (!Number.isFinite(value) || value < 0) {
        throw new Error("--retry-delay must be a non-negative number of seconds");
      }
      options.retryDelaySeconds = value;
    } else if (arg === "--include-payment-links") {
      options.includePaymentLinks = true;
    } else if (arg === "--payment-amount") {
      const value = Number(next());
      if (!Number.isFinite(value) || value < 0.5) {
        throw new Error("--payment-amount must be at least 0.5 USD");
      }
      options.paymentAmount = value;
    } else if (arg === "--verbose") {
      options.verbose = true;
    } else if (arg === "--help" || arg === "-h") {
      process.stdout.write(`Usage: node scripts/run-multi-user-smoke.mjs --base-url <url> --wallets <wallets.public.json> [options]

Runs a multi-user Portal CLI smoke suite against an AltLLM Portal API target.

Required:
  --base-url <url>              Portal API base URL
  --wallets <path>              Public wallet registry generated by prepare-test-wallets

Options:
  --cli-path <path>             Built CLI entrypoint (default: dist/cli.js)
  --start-date <yyyy-mm-dd>     Start date for usage-by-key (default: first UTC day of current month)
  --end-date <yyyy-mm-dd>       End date for usage-by-key (default: current UTC date)
  --read-burst <n>              Extra concurrent read bursts across all users (default: 1)
  --include-payment-links       Create hosted payment links and verify owner/isolation behavior
  --payment-amount <usd>        Hosted payment-link amount when enabled (default: 5)
  --command-timeout <seconds>   Per-command timeout (default: 90)
  --mutation-retries <n>        Retries for transient API-key creation failures (default: 2)
  --retry-delay <seconds>       Delay between mutation retries (default: 2)
  --verbose                     Include every compact check result in the JSON report
  -h, --help                    Show help

The suite never auto-pays and never sends on-chain transactions. It expects each
wallet registry user to already have a valid sessionFile created by login-test-wallets.
It does not read private keys and it redacts secrets from failure summaries.
`);
      process.exit(0);
    } else {
      throw new Error(`Unknown option: ${arg}`);
    }
  }

  if (!options.baseUrl) {
    throw new Error("--base-url is required");
  }
  if (!options.walletsPath) {
    throw new Error("--wallets is required");
  }

  return options;
}

function redact(value) {
  return String(value)
    .replace(/Bearer\s+[A-Za-z0-9._-]+/g, "Bearer <redacted>")
    .replace(/eyJ[A-Za-z0-9._-]+/g, "<jwt-redacted>")
    .replace(/sk-[A-Za-z0-9._-]+/g, "sk-REDACTED")
    .replace(/https?:\/\/\S+/g, "<url>")
    .slice(0, 360);
}

function percentile(sorted, p) {
  if (sorted.length === 0) return null;
  return sorted[Math.min(sorted.length - 1, Math.floor((sorted.length - 1) * p))];
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function parseJson(stdout) {
  if (!stdout.trim()) {
    return { ok: true, value: null };
  }
  try {
    return { ok: true, value: JSON.parse(stdout) };
  } catch {
    return { ok: false, value: null };
  }
}

function extractArray(data) {
  if (Array.isArray(data)) return data;
  if (data && Array.isArray(data.keys)) return data.keys;
  if (data && Array.isArray(data.data)) return data.data;
  if (data && Array.isArray(data.items)) return data.items;
  return [];
}

function extractApiKeyId(data) {
  return data?.id || data?.key_id || data?.api_key_id || data?.key?.id || null;
}

function extractPaymentLinkId(data) {
  return data?.paymentLinkId || data?.payment_link_id || data?.id || null;
}

function compactObject(data) {
  if (!data || typeof data !== "object") {
    return { type: typeof data };
  }

  const summary = {};
  for (const key of ["id", "name", "status", "balance", "total", "count", "period", "message"]) {
    if (data[key] !== undefined) summary[key] = data[key];
  }
  for (const key of ["keys", "data", "transactions", "usage", "payment_links"]) {
    if (Array.isArray(data[key])) summary[`${key}_count`] = data[key].length;
  }
  if (data.key !== undefined) summary.has_key_secret = Boolean(data.key);
  if (data.key_prefix !== undefined) summary.key_prefix = data.key_prefix;
  return summary;
}

function compactPayment(data) {
  if (!data || typeof data !== "object") {
    return { type: typeof data };
  }

  return {
    hasPaymentLinkId: Boolean(extractPaymentLinkId(data)),
    hasUrl: Boolean(data.url),
    amount: data.amount ?? null,
    currency: data.currency ?? null,
    status: data.status ?? null,
    providerStatus: data.providerStatus ?? data.provider_status ?? null,
    paymentStatus: data.paymentStatus ?? data.payment_status ?? null,
    payCurrency: data.payCurrency ?? data.pay_currency ?? null,
    discountCode: data.discountCode ?? data.promo_code ?? null,
    finalAmount: data.finalAmount ?? data.final_amount ?? null,
  };
}

function summarizeFailure(result) {
  if (result.timedOut) {
    return `timed out after ${result.timeoutSeconds}s`;
  }
  return redact(result.stderr || result.stdout || `exit ${result.code}`);
}

function isRetryableMutationFailure(result) {
  if (result.timedOut) return true;
  const text = `${result.stderr || ""}\n${result.stdout || ""}`;
  return (
    /timed out after \d+ms/i.test(text) ||
    /\b5\d\d\b/.test(text) ||
    /failed to provision api key/i.test(text)
  );
}

function runCli(params) {
  const startedAt = Date.now();
  const timeoutMs = params.commandTimeoutSeconds * 1000;
  const args = [
    params.cliPath,
    ...params.args,
    "--base-url",
    params.baseUrl,
    "--session-file",
    params.user.sessionFile,
  ];

  return new Promise((resolve) => {
    const child = spawn(process.execPath, args, {
      cwd: process.cwd(),
      env: {
        ...process.env,
        ALTLLM_HTTP_TIMEOUT_MS:
          process.env.ALTLLM_HTTP_TIMEOUT_MS ||
          String(Math.max(1000, (params.commandTimeoutSeconds - 5) * 1000)),
      },
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    let timedOut = false;
    let spawnError = null;

    const timer = setTimeout(() => {
      timedOut = true;
      child.kill("SIGTERM");
    }, timeoutMs);

    child.stdout.on("data", (chunk) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
    });
    child.on("error", (error) => {
      spawnError = error;
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      const parsed = parseJson(stdout);
      resolve({
        code,
        durationMs: Date.now() - startedAt,
        jsonOk: parsed.ok,
        json: parsed.value,
        stdout,
        stderr: spawnError ? `${stderr}\n${spawnError.message}` : stderr,
        timedOut,
        timeoutSeconds: params.commandTimeoutSeconds,
      });
    });
  });
}

async function createApiKeyWithRetry(user, label, baseName, params, recorder) {
  let lastResult = null;
  const maxAttempts = params.mutationRetries + 1;
  for (let attempt = 1; attempt <= maxAttempts; attempt += 1) {
    const name = attempt === 1 ? baseName : `${baseName}-retry-${attempt}`;
    const result = await runCli({
      ...params,
      user,
      args: ["create-api-key", "--name", name],
    });
    lastResult = result;
    const ok = result.code === 0 && result.jsonOk && !result.timedOut;
    if (ok) {
      recorder.record({
        user: user.name,
        label,
        ok: true,
        code: result.code,
        durationMs: result.durationMs,
        summary: {
          ...compactObject(result.json),
          attempts: attempt,
        },
      });
      return result;
    }

    if (attempt >= maxAttempts || !isRetryableMutationFailure(result)) {
      break;
    }
    await sleep(params.retryDelaySeconds * 1000);
  }

  recorder.record({
    user: user.name,
    label,
    ok: false,
    code: lastResult?.code ?? null,
    durationMs: lastResult?.durationMs ?? 0,
    summary: {
      attempts: maxAttempts,
      error: lastResult ? summarizeFailure(lastResult) : "create-api-key did not run",
    },
  });
  return lastResult;
}

function makeRecorder() {
  const results = [];
  return {
    results,
    record(check) {
      results.push(check);
    },
    async expectCliOk(user, label, args, params, summarizer = compactObject) {
      const result = await runCli({ ...params, user, args });
      const ok = result.code === 0 && result.jsonOk && !result.timedOut;
      results.push({
        user: user.name,
        label,
        ok,
        code: result.code,
        durationMs: result.durationMs,
        summary: ok ? summarizer(result.json) : summarizeFailure(result),
      });
      return result;
    },
  };
}

async function runUserFlow(user, params, recorder) {
  const reads = [
    ["credit", ["credit"]],
    ["transactions", ["transactions"]],
    ["usage-summary", ["usage-summary"]],
    ["usage-timeline", ["usage-timeline"]],
    ["usage-by-model", ["usage-by-model"]],
    [
      "usage-by-key",
      ["usage-by-key", "--start-date", params.startDate, "--end-date", params.endDate],
    ],
    ["list-api-keys", ["list-api-keys"]],
  ];

  for (const [label, args] of reads) {
    await recorder.expectCliOk(user, label, args, params);
  }

  const keyName = `multi-user-smoke-${user.name}-${Date.now()}`;
  const created = await createApiKeyWithRetry(
    user,
    "create-api-key",
    keyName,
    params,
    recorder
  );
  const keyId = extractApiKeyId(created.json);
  if (!keyId) {
    recorder.record({
      user: user.name,
      label: "extract-api-key-id",
      ok: false,
      code: null,
      durationMs: 0,
      summary: "create-api-key did not return an API key id",
    });
    return;
  }

  try {
    await recorder.expectCliOk(user, "get-api-key", ["get-api-key", "--key-id", keyId], params);
    await recorder.expectCliOk(
      user,
      "update-api-key-name",
      ["update-api-key", "--key-id", keyId, "--name", `${keyName}-updated`],
      params
    );
    await recorder.expectCliOk(
      user,
      "disable-api-key",
      ["update-api-key", "--key-id", keyId, "--status", "disabled"],
      params
    );
    await recorder.expectCliOk(
      user,
      "enable-api-key",
      ["update-api-key", "--key-id", keyId, "--status", "active"],
      params
    );
    const listAfterCreate = await recorder.expectCliOk(
      user,
      "list-after-create",
      ["list-api-keys"],
      params
    );
    const visible = extractArray(listAfterCreate.json).some(
      (key) => String(key.id || key.key_id) === String(keyId)
    );
    recorder.record({
      user: user.name,
      label: "created-key-visible-to-owner",
      ok: visible,
      code: null,
      durationMs: 0,
      summary: { key_id_seen: visible },
    });
  } finally {
    const revoked = await runCli({
      ...params,
      user,
      args: ["revoke-api-key", "--key-id", keyId],
    });
    const revokeOk = revoked.code === 0 && revoked.jsonOk && !revoked.timedOut;
    recorder.record({
      user: user.name,
      label: "revoke-api-key",
      ok: revokeOk,
      code: revoked.code,
      durationMs: revoked.durationMs,
      summary: revokeOk ? compactObject(revoked.json) : summarizeFailure(revoked),
    });
  }

  const finalList = await recorder.expectCliOk(
    user,
    "list-after-revoke",
    ["list-api-keys"],
    params
  );
  const stillActive = extractArray(finalList.json).some(
    (key) => String(key.id || key.key_id) === String(keyId)
  );
  recorder.record({
    user: user.name,
    label: "revoked-key-hidden-from-active-list",
    ok: !stillActive,
    code: null,
    durationMs: 0,
    summary: { active_after_revoke: stillActive },
  });
}

async function runConcurrentReadBurst(users, params, recorder) {
  const readCommands = [
    ["credit", ["credit"]],
    ["transactions", ["transactions"]],
    ["usage-summary", ["usage-summary"]],
    ["usage-by-model", ["usage-by-model"]],
    ["list-api-keys", ["list-api-keys"]],
  ];

  for (let burst = 1; burst <= params.readBurst; burst += 1) {
    const checks = [];
    for (const user of users) {
      for (const [label, args] of readCommands) {
        checks.push(
          runCli({ ...params, user, args }).then((result) => {
            const ok = result.code === 0 && result.jsonOk && !result.timedOut;
            return {
              user: user.name,
              label: `concurrent-${label}`,
              ok,
              code: result.code,
              durationMs: result.durationMs,
              summary: ok ? compactObject(result.json) : summarizeFailure(result),
            };
          })
        );
      }
    }
    for (const check of await Promise.all(checks)) {
      recorder.record({ ...check, burst });
    }
  }
}

async function runCrossUserIsolation(users, params, recorder) {
  if (users.length < 2) return;

  const owner = users[0];
  const other = users[1];
  const keyName = `multi-user-isolation-${Date.now()}`;
  const created = await createApiKeyWithRetry(
    owner,
    "owner-create-key-for-cross-user-test",
    keyName,
    params,
    recorder
  );
  const keyId = extractApiKeyId(created.json);
  if (!keyId) return;

  try {
    const otherGet = await runCli({
      ...params,
      user: other,
      args: ["get-api-key", "--key-id", keyId],
    });
    recorder.record({
      user: other.name,
      label: "other-user-cannot-read-owner-key",
      ok: otherGet.code !== 0,
      code: otherGet.code,
      durationMs: otherGet.durationMs,
      summary: otherGet.code === 0 ? "unexpected success" : summarizeFailure(otherGet),
    });
  } finally {
    await recorder.expectCliOk(
      owner,
      "owner-revoke-cross-user-test-key",
      ["revoke-api-key", "--key-id", keyId],
      params
    );
  }
}

async function runPaymentLinkChecks(users, params, recorder) {
  if (!params.includePaymentLinks || users.length === 0) return;

  const owner = users[0];
  const other = users[1] || users[0];
  const amount = String(params.paymentAmount);
  const created = await recorder.expectCliOk(
    owner,
    "owner-create-payment-link-for-cross-user-test",
    ["topup-crypto", "--amount", amount],
    params,
    compactPayment
  );
  const paymentLinkId = extractPaymentLinkId(created.json);
  if (paymentLinkId) {
    await recorder.expectCliOk(
      owner,
      "owner-can-read-own-payment-link",
      ["payment-status", "--payment-link-id", paymentLinkId],
      params,
      compactPayment
    );

    if (other !== owner) {
      const otherStatus = await runCli({
        ...params,
        user: other,
        args: ["payment-status", "--payment-link-id", paymentLinkId],
      });
      recorder.record({
        user: other.name,
        label: "other-user-cannot-read-owner-payment-link",
        ok: otherStatus.code !== 0,
        code: otherStatus.code,
        durationMs: otherStatus.durationMs,
        summary:
          otherStatus.code === 0 ? "unexpected success" : summarizeFailure(otherStatus),
      });
    }
  }

  const checks = users.map(async (user) => {
    const createdLink = await runCli({
      ...params,
      user,
      args: ["topup-crypto", "--amount", amount],
    });
    const createdOk = createdLink.code === 0 && createdLink.jsonOk && !createdLink.timedOut;
    const linkId = createdOk ? extractPaymentLinkId(createdLink.json) : null;
    let statusOk = false;
    let statusSummary = null;
    if (linkId) {
      const status = await runCli({
        ...params,
        user,
        args: ["payment-status", "--payment-link-id", linkId],
      });
      statusOk = status.code === 0 && status.jsonOk && !status.timedOut;
      statusSummary = statusOk ? compactPayment(status.json) : summarizeFailure(status);
    }
    return {
      user: user.name,
      label: "concurrent-payment-link",
      ok: createdOk && statusOk,
      code: createdLink.code,
      durationMs: createdLink.durationMs,
      summary: {
        create: createdOk ? compactPayment(createdLink.json) : summarizeFailure(createdLink),
        status: statusSummary,
      },
    };
  });
  for (const check of await Promise.all(checks)) {
    recorder.record(check);
  }
}

function summarize(results, params, users) {
  const failed = results.filter((result) => !result.ok);
  const durations = results
    .filter((result) => typeof result.durationMs === "number" && result.durationMs > 0)
    .map((result) => result.durationMs)
    .sort((a, b) => a - b);
  const byLabel = {};
  for (const result of results) {
    byLabel[result.label] ||= { passed: 0, failed: 0 };
    if (result.ok) byLabel[result.label].passed += 1;
    else byLabel[result.label].failed += 1;
  }

  const report = {
    ok: failed.length === 0,
    baseUrl: params.baseUrl,
    users: users.map((user) => ({ name: user.name, address: user.address })),
    options: {
      startDate: params.startDate,
      endDate: params.endDate,
      readBurst: params.readBurst,
      includePaymentLinks: params.includePaymentLinks,
      paymentAmount: params.includePaymentLinks ? params.paymentAmount : null,
      mutationRetries: params.mutationRetries,
    },
    totalChecks: results.length,
    passed: results.length - failed.length,
    failed: failed.length,
    latencyMs: {
      p50: percentile(durations, 0.5),
      p95: percentile(durations, 0.95),
      p99: percentile(durations, 0.99),
    },
    byLabel,
    failures: failed.map((result) => ({
      user: result.user,
      label: result.label,
      code: result.code,
      summary: result.summary,
    })),
  };

  if (params.verbose) {
    report.results = results;
  }

  return report;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const walletsPath = resolve(options.walletsPath);
  const cliPath = resolve(options.cliPath);
  const wallets = JSON.parse(await readFile(walletsPath, "utf8"));
  const users = wallets.users;
  if (!Array.isArray(users) || users.length === 0) {
    throw new Error("--wallets must contain a non-empty users array");
  }

  const params = {
    ...options,
    cliPath,
  };
  const recorder = makeRecorder();

  for (const user of users) {
    await runUserFlow(user, params, recorder);
  }
  await runCrossUserIsolation(users, params, recorder);
  await runConcurrentReadBurst(users, params, recorder);
  await runPaymentLinkChecks(users, params, recorder);

  const report = summarize(recorder.results, params, users);
  process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
  if (!report.ok) {
    process.exit(1);
  }
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  process.stderr.write(`error: ${redact(message)}\n`);
  process.exit(1);
});
