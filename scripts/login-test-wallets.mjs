#!/usr/bin/env node
import { mkdir, readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { spawn } from "node:child_process";

import { privateKeyToAccount } from "viem/accounts";

function parseArgs(argv) {
  const options = {
    cliPath: "dist/cli.js",
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = () => {
      const value = argv[index + 1];
      if (!value || value.startsWith("--")) {
        throw new Error(`${arg} requires a value`);
      }
      index += 1;
      return value;
    };

    if (arg === "--base-url") {
      options.baseUrl = next();
    } else if (arg === "--wallets") {
      options.walletsPath = next();
    } else if (arg === "--cli-path") {
      options.cliPath = next();
    } else if (arg === "--help" || arg === "-h") {
      process.stdout.write(`Usage: node scripts/login-test-wallets.mjs --base-url <url> --wallets <wallets.public.json> [options]

Options:
  --base-url <url>       Portal API base URL
  --wallets <path>       Public wallet registry generated by prepare-test-wallets
  --cli-path <path>      Built CLI entrypoint (default: dist/cli.js)
  -h, --help             Show help

The script reads private keys from each user's privateKeyEnv environment variable.
It never prints private keys.
`);
      process.exit(0);
    } else {
      throw new Error(`Unknown option: ${arg}`);
    }
  }

  if (!options.baseUrl) {
    throw new Error("--base-url is required");
  }
  if (!options.walletsPath) {
    throw new Error("--wallets is required");
  }

  return options;
}

function runCli(cliPath, args) {
  const startedAt = Date.now();
  return new Promise((resolve) => {
    const child = spawn(process.execPath, [cliPath, ...args], {
      cwd: process.cwd(),
      env: process.env,
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (chunk) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
    });
    child.on("close", (code) => {
      resolve({
        code,
        stdout,
        stderr,
        durationMs: Date.now() - startedAt,
      });
    });
  });
}

function parseJsonOutput(result, phase) {
  try {
    return JSON.parse(result.stdout);
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`${phase} returned invalid JSON: ${detail}`);
  }
}

async function loginUser(params) {
  const privateKey = process.env[params.user.privateKeyEnv]?.trim();
  if (!privateKey) {
    throw new Error(`Missing environment variable ${params.user.privateKeyEnv}`);
  }

  await mkdir(dirname(params.user.sessionFile), { recursive: true, mode: 0o700 });

  const prepare = await runCli(params.cliPath, [
    "login-wallet",
    "--prepare",
    "--base-url",
    params.baseUrl,
    "--wallet-address",
    params.user.address,
    "--session-file",
    params.user.sessionFile,
  ]);
  if (prepare.code !== 0) {
    throw new Error(`prepare failed: ${prepare.stderr.trim()}`);
  }

  const challenge = parseJsonOutput(prepare, "prepare");
  const account = privateKeyToAccount(privateKey);
  const signature = await account.signMessage({ message: challenge.message });

  const verify = await runCli(params.cliPath, [
    "login-wallet",
    "--base-url",
    params.baseUrl,
    "--wallet-address",
    params.user.address,
    "--nonce",
    challenge.nonce,
    "--signature",
    signature,
    "--session-file",
    params.user.sessionFile,
  ]);
  if (verify.code !== 0) {
    throw new Error(`verify failed: ${verify.stderr.trim()}`);
  }

  const login = parseJsonOutput(verify, "verify");
  return {
    name: params.user.name,
    address: params.user.address,
    sessionFile: params.user.sessionFile,
    user: login.user,
    durationMs: prepare.durationMs + verify.durationMs,
  };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const cliPath = resolve(options.cliPath);
  const wallets = JSON.parse(await readFile(options.walletsPath, "utf8"));
  const users = wallets.users;
  if (!Array.isArray(users) || users.length === 0) {
    throw new Error("--wallets must contain a non-empty users array");
  }

  const results = [];
  for (const user of users) {
    try {
      const result = await loginUser({
        baseUrl: options.baseUrl,
        cliPath,
        user,
      });
      results.push({ ok: true, ...result });
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      results.push({
        ok: false,
        name: user.name,
        address: user.address,
        sessionFile: user.sessionFile,
        error: message,
      });
    }
  }

  const failed = results.filter((result) => !result.ok);
  process.stdout.write(
    `${JSON.stringify(
      {
        ok: failed.length === 0,
        baseUrl: options.baseUrl,
        total: results.length,
        passed: results.length - failed.length,
        failed: failed.length,
        results,
      },
      null,
      2
    )}\n`
  );

  if (failed.length > 0) {
    process.exit(1);
  }
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  process.stderr.write(`error: ${message}\n`);
  process.exit(1);
});
